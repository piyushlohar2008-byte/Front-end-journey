// Strings in js 
// String is immutable it does not changes entire program
// Strings are created using 3 different ways in js -

// 1. single quote string -
let name = 'Shraddha';
console.log(name);

// 2. double quote string - 
let name2 = "Shravani";
console.log(name2);

// 3. Template -
// Modern string method to create string
let friend = `${name} is friend of ${name2}`;
console.log(friend);
let myFriend = `My friends is ${name} and ${name2}`;
console.log(myFriend);

// Backword slash with quotes and next line in string
let sentence = "\"JavaScript\" is best language";
console.log(sentence);

// \n is used to place content in next line 
let nextLine = "Coding is not for \nbeginners";
console.log(nextLine);